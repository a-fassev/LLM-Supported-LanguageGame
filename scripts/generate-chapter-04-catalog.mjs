function writeJson(rel, value) {
  const filePath = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

/** Ensure public/content-assets dirs exist for each catalog key (PNG drop-in later). */
function collectChapter04AssetKeys(chapterBg, questRows) {
  const keys = new Set([chapterBg, ...FOTO_FIGURE_KEYS]);
  for (const q of questRows) {
    keys.add(q.background);
    for (const [prop, value] of Object.entries(q)) {
      if (prop.startsWith("bg") && typeof value === "string") {
        keys.add(value);
      }
    }
  }
  return [...keys].sort();
}

function ensureChapter04AssetPlaceholders(assetKeys) {
  for (const assetKey of assetKeys) {
    const pngPath = path.join(ASSETS_ROOT, `${assetKey}.png`);
    fs.mkdirSync(path.dirname(pngPath), { recursive: true });
    if (!fs.existsSync(pngPath)) {
      const gitkeep = path.join(path.dirname(pngPath), ".gitkeep");
      if (!fs.existsSync(gitkeep)) {
        fs.writeFileSync(gitkeep, "", "utf8");
      }
    }
  }
  const manifestPath = path.join(ASSETS_ROOT, "chapters/04/ASSET_KEYS.txt");
  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(
    manifestPath,
    [
      "# PNG paths for chapter 04 (keys in JSON omit .png). Regenerated by generate-chapter-04-catalog.mjs",
      "",
      ...assetKeys.map((key) => `${key}.png`),
      "",
    ].join("\n"),
    "utf8",
  );
}

function story(chapterId, questId, n, bg, text) {
  const nn = String(n).padStart(2, "0");
  return {
    id: `${chapterId}-${questId}-scene-${nn}`,
    scene_type: "story",
    screen_type: "info",
    background: bg,
    content: { text },
  };
}

function gap(answers, maxLength = 64) {
  return { kind: "gap", maxLength, correctAnswers: answers };
}

function freetextEvaluation(criteria, registerTarget = "informal") {
  return {
    grammarWeight: 1,
    vocabularyWeight: 1,
    registerWeight: 1,
    taskFulfillmentWeight: 1,
    passThreshold: 0.65,
    registerTarget,
    scoringPolicy: "threshold_pass",
    maxPoints: 5,
    evaluationCriteria: criteria,
  };
}

function tu(text) {
  return `Tu\n${text}`;
}

function npc(name, dialogue) {
  return `${name}\n${dialogue}`;
}

function mcQuestion(id, prompt, optionLabels, correctIndex) {
  const letters = ["a", "b", "c", "d"];
  const correctLetter = letters[correctIndex];
  return {
    id,
    selectionMode: "single",
    preserveOptionOrder: true,
    prompt,
    options: optionLabels.map((label, i) => ({
      id: `${id}-opt-${letters[i]}`,
      label,
    })),
    correctOptionIds: [`${id}-opt-${correctLetter}`],
  };
}

/** Build error_spotting segments for one numbered Sara quote (spacing rules for catalog). */
function saraErrorLine(num, before, errorPhrase, after, corrections) {
  const opener = num === 1 ? `${num}. Sara: „${before}` : ` ${num}. Sara: „${before}`;
  return [
    { id: `es${num}-a`, text: opener, isError: false },
    {
      id: `es${num}-err`,
      text: ` ${errorPhrase}`,
      isError: true,
      acceptedCorrections: corrections,
    },
    { id: `es${num}-b`, text: ` ${after}"`, isError: false },
  ];
}

function saraCorrectLine(num, fullQuote) {
  const text =
    num === 1 ? `${num}. Sara: „${fullQuote}"` : ` ${num}. Sara: „${fullQuote}"`;
  return [{ id: `es${num}-all`, text, isError: false }];
}

