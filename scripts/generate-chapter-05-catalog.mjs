const ROOT = path.join(process.cwd(), "lib/content/chapters/chapter-05");
const ASSETS_ROOT = path.join(process.cwd(), "public/content-assets");
const CHAPTER_ID = "chapter-05";

if (fs.existsSync(ROOT)) {
  fs.rmSync(ROOT, { recursive: true, force: true });
}

function writeJson(rel, value) {
  const filePath = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

function collectChapter05AssetKeys(chapterBg, questRows) {
  const keys = new Set([chapterBg]);
  for (const q of questRows) {
    keys.add(q.background);
    for (const [prop, value] of Object.entries(q)) {
      if (prop.startsWith("bg") && typeof value === "string") {
        keys.add(value);
      }
    }
  }
  return [...keys].sort();
}

function ensureChapter05AssetPlaceholders(assetKeys) {
  for (const assetKey of assetKeys) {
    const pngPath = path.join(ASSETS_ROOT, `${assetKey}.png`);
    fs.mkdirSync(path.dirname(pngPath), { recursive: true });
    if (!fs.existsSync(pngPath)) {
      const gitkeep = path.join(path.dirname(pngPath), ".gitkeep");
      if (!fs.existsSync(gitkeep)) {
        fs.writeFileSync(gitkeep, "", "utf8");
      }
    }
  }
  const manifestPath = path.join(ASSETS_ROOT, "chapters/05/ASSET_KEYS.txt");
  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(
    manifestPath,
    [
      "# PNG paths for chapter 05 (keys in JSON omit .png). Regenerated by generate-chapter-05-catalog.mjs",
      "",
      ...assetKeys.map((key) => `${key}.png`),
      "",
    ].join("\n"),
    "utf8",
  );
}

function story(chapterId, questId, n, bg, text) {
  const nn = String(n).padStart(2, "0");
  return {
    id: `${chapterId}-${questId}-scene-${nn}`,
    scene_type: "story",
    screen_type: "info",
    background: bg,
    content: { text },
  };
}

function gap(answers, maxLength = 80) {
  return { kind: "gap", maxLength, correctAnswers: answers };
}

function optionalGap(maxLength = 32) {
  return { kind: "gap", placeholder: "lascia vuoto", maxLength, optional: true, correctAnswers: [""] };
}

function quoteItalianDialogue(text) {
  const trimmed = text.trim();
  if (trimmed.startsWith("„") || trimmed.startsWith('"')) {
    return trimmed;
  }
  return `„${trimmed}"`;
}

function tu(text) {
  return `Tu\n${quoteItalianDialogue(text)}`;
}

function npc(name, dialogue) {
  return `${name}\n${quoteItalianDialogue(dialogue)}`;
}

function mcQuestion(id, prompt, optionLabels, correctIndex) {
  const letters = ["a", "b", "c", "d"];
  const correctLetter = letters[correctIndex];
  return {
    id,
    selectionMode: "single",
    preserveOptionOrder: true,
    prompt,
    options: optionLabels.map((label, i) => ({
      id: `${id}-opt-${letters[i]}`,
      label,
    })),
    correctOptionIds: [`${id}-opt-${correctLetter}`],
  };
}

